"""Regenerate the fixed-point lookup tables. The Win16 build uses SFTABLE.H."""
import math
from pathlib import Path


def table(name, ctype, values):
    result = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for start in range(0, len(values), 8):
        result.append("    " + ", ".join(map(str, values[start:start + 8])) + ",")
    return "\n".join(result + ["};"])


tables = [
    table("sf_pitch_table", "uint32_t",
          [round((1 << 24) * 2 ** (i / 1200)) for i in range(0, 1201, 10)]),
    table("sf_pan_table", "uint16_t",
          [round(32768 * math.sqrt(i / 256)) for i in range(257)]),
]
for rate in (44100, 48000):
    tables.append(table(f"sf_tan_{rate}", "int32_t",
                        [round(65536 * math.tan(math.pi * 8.176 * 2 ** (i / 1200) / rate))
                         for i in range(0, 13501, 50)]))
data = "/* Generated by MKTABLES.PY. */\n" + "\n\n".join(tables) + "\n"
Path(__file__).with_name("SFTABLE.H").write_bytes(data.replace("\n", "\r\n").encode("ascii"))
